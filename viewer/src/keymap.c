int sdv_keymap_lookup(SDL_Scancode sc, struct sdv_key *out)
{
    if (sc <= SDL_SCANCODE_UNKNOWN || sc >= SDL_NUM_SCANCODES || table[sc].vk == 0)
        return -1;
    *out = table[sc];
    return 0;
}
